"""Does the policy's action, converted as the fine-tune converts it, reproduce the
action the corpus was recorded with?

THE CHECK THAT WOULD HAVE SAVED THREE DAYS. The fine-tune reads chrono->policy as
`q = SIGN * s[:, JP][:, C2I]` and writes policy->chrono by scattering through C2I. The
scatter omitted SIGN, so the joint target handed to the surrogate was NEGATED -- every
branch step, every arm, both terrains. Measured against an episode this same policy
generated: as-written corr -0.8313, with SIGN +0.8313.

Nothing else in the pipeline could see it:
  - the displacement-matched RANDOM CONTROL never enters the branch loop, so three flat
    controls coexisted with every gradient-trained arm being 4-8x worse;
  - the OPEN-LOOP AUDIT fed RECORDED actions, so it certified a surrogate that was
    genuinely fine (2.9-3.3x better than persistence at the branch horizon).
Both guards were sound. The defect lived in the INTERFACE between them, which neither
touched. Guard the endpoints AND the conversion that joins them.

The corpus is generated BY the base policy, so this is a closed loop with a known
answer: feed recorded observations, and the reconstructed target must match the
recorded one. A negative correlation is a sign error; a low positive one is a scaling
or ordering error.
"""
import argparse, csv, json, sys
import numpy as np, torch

sys.path.insert(0, "src")
from nedm.quadruped.policy_batched import BatchedGo2Policy
from nedm.quadruped.imported_policy import (CHRONO_TO_IMPORTED, SIGN, IMPORTED_DEFAULTS,
    ANG_VEL_SCALE, CMD_SCALE, DOF_POS_SCALE, DOF_VEL_SCALE, ACTION_SCALE)

ap = argparse.ArgumentParser()
ap.add_argument("--policy", required=True, help="TorchScript base policy")
ap.add_argument("--metadata", required=True, help="processed dataset metadata.json")
ap.add_argument("--index", required=True, help="dataset_index.json with absolute csv_path")
ap.add_argument("--episodes", type=int, default=3)
ap.add_argument("--steps", type=int, default=300)
ap.add_argument("--min-corr", type=float, default=0.5,
                help="fail below this; a NEGATIVE correlation means a sign error")
a = ap.parse_args()

md = json.load(open(a.metadata))
sf, af = md["state_fields"], md["action_fields"]
ix = {n: i for i, n in enumerate(sf)}
MOTOR = [c[len("joint_"):-len("_target_rad")] for c in af if c.endswith("_target_rad")]
eps = json.load(open(a.index))["episodes"][:a.episodes]

policy = BatchedGo2Policy(torch.jit.load(a.policy, map_location="cpu"))
C2I = torch.tensor(CHRONO_TO_IMPORTED, dtype=torch.long)
DEF = torch.tensor(np.asarray(IMPORTED_DEFAULTS, dtype=np.float32))
T = lambda v: torch.as_tensor(np.asarray(v, dtype=np.float32))
ANGS, CMDS, DPS, DVS, ACTS = T(ANG_VEL_SCALE), T(CMD_SCALE), T(DOF_POS_SCALE), T(DOF_VEL_SCALE), T(ACTION_SCALE)
JP = [ix[f"joint_{n}_pos_rad"] for n in MOTOR]
JV = [ix[f"joint_{n}_vel_radps"] for n in MOTOR]
ANG = [ix["roll_rate_radps"], ix["ang_vel_body_y_radps"], ix["yaw_rate_radps"]]
GRV = [ix["grav_body_x"], ix["grav_body_y"], ix["grav_body_z"]]

mine, rec = [], []
for e in eps:
    rows = list(csv.DictReader(open(e["csv_path"])))
    hist = policy.initial_history(1, "cpu"); prev = torch.zeros(1, 12)
    start = 401 if 401 % 2 else 402                     # post-warmup, control on ODD rows
    for i in range(start, min(start + 2 * a.steps, len(rows) - 2), 2):
        s = torch.tensor(np.array([float(rows[i][f] ) for f in sf], dtype=np.float32)).unsqueeze(0)
        cmd = torch.tensor([[float(rows[i]["cmd_vx_mps"]), float(rows[i]["cmd_vy_mps"]),
                             float(rows[i]["cmd_wz_radps"])]])
        obs = torch.cat([s[:, ANG] * ANGS, s[:, GRV], cmd * CMDS,
                         (SIGN * s[:, JP][:, C2I] - DEF) * DPS,
                         SIGN * s[:, JV][:, C2I] * DVS, prev], dim=1)
        with torch.no_grad():
            act, hist = policy(obs, hist)
        prev = act
        mine.append(torch.zeros(12).index_copy(
            0, C2I, SIGN * (act * ACTS + DEF)[0]).numpy())
        rec.append(np.array([float(rows[i][f"joint_{n}_target_rad"]) for n in MOTOR],
                            dtype=np.float32))

mine, rec = np.array(mine), np.array(rec)
corr = float(np.corrcoef(mine.ravel(), rec.ravel())[0, 1])
rms = float(np.sqrt(((mine - rec) ** 2).mean()))
print(f"  steps compared     {len(mine)}")
print(f"  RMS error          {rms:.5f} rad")
print(f"  correlation        {corr:+.4f}")
if corr < 0:
    raise SystemExit(f"FATAL: correlation {corr:+.4f} is NEGATIVE -- the reconstructed "
                     f"target is the negation of the recorded one. A SIGN is missing "
                     f"from the policy->surrogate conversion.")
if corr < a.min_corr:
    raise SystemExit(f"FATAL: correlation {corr:+.4f} below {a.min_corr} -- the policy's "
                     f"action does not reproduce the action that generated this corpus. "
                     f"Suspect joint ordering (C2I), scaling (ACTION_SCALE) or defaults.")
print(f"  OK: the fine-tune's conversion reproduces the recorded action.")
